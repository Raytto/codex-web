import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const output = process.env.CWW_BROWSER_TEST_OUTPUT || fs.mkdtempSync(path.join(os.tmpdir(), 'opportunity-ui-report-'));
fs.mkdirSync(output, { recursive: true, mode: 0o700 });
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'opportunity-ui-'));
const require = createRequire(repo + '/package.json');
const { createApp } = await import(repo + '/dist-server/server/app.js');
const { OpportunityStore, contentInput } = await import(repo + '/dist-server/server/opportunity-store.js');
const cache = process.env.PLAYWRIGHT_BROWSERS_PATH || path.join(os.homedir(), '.cache/ms-playwright');
const playwrightRoot = process.env.PLAYWRIGHT_MODULE_PATH || fs.readdirSync(cache + '/.links').map(n => fs.readFileSync(cache + '/.links/' + n, 'utf8').trim()).find(p => fs.existsSync(p + '/index.mjs'));
process.env.PLAYWRIGHT_BROWSERS_PATH = cache;
const { chromium } = await import(playwrightRoot + '/index.mjs');

const instance = createApp({ projectRoot: repo, basePath: '/codex-web', dataRoot: root + '/data', tenantRoot: root + '/tenants', username: 'pp', passwordHash: require('bcryptjs').hashSync('draft-test', 4), sessionSecret: 'opportunity-draft-test-secret-atleast32chars', queueAutoStart: false, minimumFreeDiskBytes: 0 });
const server = instance.app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
const origin = 'http://127.0.0.1:' + server.address().port + '/codex-web';
const report = { checks: [], pageErrors: [] }; let browser;
const deadline = setTimeout(() => { throw new Error('Research draft browser test timed out'); }, 120000);
try {
  browser = await chromium.launch({ headless: true, ignoreDefaultArgs: ['--disable-dev-shm-usage'], args: ['--disable-gpu'], env: { ...process.env, HOME: root, TMPDIR: root } });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const login = await context.request.post(origin + '/api/auth/login', { data: { username: 'pp', password: 'draft-test' } }); assert.equal(login.status(), 200);
  const session = await login.json();
  const api = async (method, url, data) => {
    const r = await context.request.fetch(origin + '/api' + url, { method, headers: { Origin: new URL(origin).origin, 'X-CSRF-Token': session.csrfToken }, ...(data === undefined ? {} : { data }) });
    assert.ok(r.ok(), url + ': ' + r.status()); return r.status() === 204 ? null : r.json();
  };
  const prefs = await api('GET', '/user-settings/features');
  await api('PUT', '/user-settings/features', { ...prefs, opportunityCards: true });
  const user = session.accountId;
  const project = (await api('GET', '/projects')).projects.find(p => p.executor_id === 'tenant-local');
  const store = new OpportunityStore(instance.db);
  const target=instance.db.createProject(crypto.randomUUID(),user,'另一个研究工程',root+'/research','tenant-local');
  const topic = (await api('POST', '/opportunities/topics', { requestKey: crypto.randomUUID(), name: '研究草稿验收', project_id: project.id, goal: '独立浏览器验收' })).topic;
  const source = (await api('POST', '/conversations', { projectId: project.id, reuseEmpty: false })).conversation;
  await api('PATCH', '/conversations/' + source.id, { title: '普通会话导航验收' });
  const batch = store.begin(user, topic.id, source.id, null);
  const content = contentInput.parse({ title: '研究草稿测试卡片', summary: '测试手动发起研究', audience: '浏览器验收', problem: '合成测试问题', mechanism: '绘制并试戴帽子', value: '验证草稿', fit: '小型测试', facts: '合成数据', assumptions: '假设', doubt: '不用于业务', validation: '输入框编辑后发送', difference: '独立测试机制', category: '测试', keywords: ['测试'], sources: [] });
  const idea = store.ingest(user, batch.id, source.id, [{ key: 'fixture', content }])[0].idea;
  store.feedback(user, idea.id, { requestKey: crypto.randomUUID(), revision: idea.revision, action: 'kept', rating: 4, note: '已保存思路：先验证自由绘画\n再试戴' });
  const page = await context.newPage(); page.setDefaultTimeout(15000); page.on('pageerror', e => report.pageErrors.push(String(e)));
  const input = () => page.locator('.composer:visible textarea');
  const count = (table, cid) => instance.db.sqlite.prepare(`SELECT count(*) n FROM ${table} WHERE conversation_id=?`).get(cid).n;
  const openCard = async () => {
    await page.getByRole('region', { name: '机会卡片', exact: true }).locator(`[data-opportunity-topic="${topic.id}"] .project-select`).click();
    const workspace = page.locator('.opportunity-workspace:visible');
    await workspace.getByRole('navigation',{name:'已处理卡片总览'}).getByRole('button', { name: /^已保留/ }).click();
    await workspace.locator(`[data-opportunity-idea="${idea.id}"]`).getByRole('button', { name: '查看详情', exact: true }).click();
    await page.getByRole('dialog').getByRole('textbox', { name: '反馈（可选）' }).waitFor();
  };
  await page.goto(origin);
  await page.locator('[data-extension-group="opportunities"] .extension-toggle').click();
  await openCard();
  await page.getByRole('dialog').getByRole('combobox',{name:'研究工程',exact:true}).selectOption(target.id);
  let response = page.waitForResponse(r => r.url().endsWith(`/ideas/${idea.id}/research`) && r.request().method() === 'POST');
  await page.getByRole('dialog').getByRole('button', { name: '深入研究', exact: true }).click();
  const firstResponse=await (await response).json();
  assert.equal(firstResponse.projectId,target.id);
  const first = firstResponse.conversationId;
  assert.equal(instance.db.getConversation(first).project_id,target.id);
  assert.equal(store.detail(user,idea.id).research[0].project_id,target.id);
  assert.equal(store.view(user,topic.id,'working').ideas[0].work.research.project_id,target.id);
  await input().waitFor();
  await page.waitForFunction(() => document.querySelector('.composer textarea')?.value.includes('已保存思路'));
  const initial = await input().inputValue();
  assert.ok(initial.includes('评分：4 星')); assert.ok(initial.includes('先验证自由绘画')); assert.ok(initial.includes(idea.id));
  assert.ok(!initial.includes('本次填写的评价'));
  for (const table of ['pending_prompts', 'messages', 'jobs']) assert.equal(count(table, first), 0);
  report.checks.push('click_creates_persistent_feedback_draft_without_messages_or_jobs');
  assert.equal(await page.getByRole('button', { name: '返回机会卡片', exact: true }).count(), 0);
  assert.equal(await page.locator('.opportunity-return').count(), 0);
  const edited = initial + '\n用户补充：先做平板原型';
  const saved = page.waitForResponse(r => r.url().endsWith(`/conversations/${first}/draft`) && r.request().method() === 'PUT');
  await input().fill(edited); await saved;
  await page.reload(); await input().waitFor();
  await page.waitForFunction(text => document.querySelector('.composer textarea')?.value === text, edited);
  for (const table of ['pending_prompts', 'messages', 'jobs']) assert.equal(count(table, first), 0);
  report.checks.push('edited_draft_survives_reload_without_execution');
  await page.locator('.conversation-select').filter({ hasText: '普通会话导航验收' }).click();
  await input().waitFor();
  assert.equal(await page.getByRole('button', { name: '返回机会卡片', exact: true }).count(), 0);
  assert.equal(await page.locator('.opportunity-return').count(), 0);
  report.checks.push('direct_navigation_has_no_return_bar_in_research_or_other_conversation');
  await openCard();
  await page.getByRole('dialog').getByRole('textbox', { name: '反馈（可选）' }).fill('未保存补充：让孩子改帽子的轮廓');
  await page.getByRole('dialog').getByRole('combobox', { name: '评分', exact: true }).selectOption('5');
  response = page.waitForResponse(r => r.url().endsWith(`/ideas/${idea.id}/research`) && r.request().method() === 'POST');
  await page.getByRole('dialog').getByRole('button', { name: '深入研究', exact: true }).click();
  const second = (await (await response).json()).conversationId;
  await page.waitForFunction(() => document.querySelector('.composer textarea')?.value.includes('未保存补充'));
  assert.notEqual(first, second); assert.equal(instance.db.getComposerDraft(first).content, edited);
  assert.ok((await input().inputValue()).includes('尚未保存到卡片'));
  assert.equal(store.idea(user, idea.id).rating, 4); assert.ok(store.idea(user, idea.id).note.startsWith('已保存思路'));
  for (const table of ['pending_prompts', 'messages', 'jobs']) assert.equal(count(table, second), 0);
  report.checks.push('unsaved_feedback_included_without_changing_saved_feedback_or_other_draft');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await input().isEditable(), true);
  await input().fill('最终手动发送的研究任务');
  const send = page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes(`/conversations/${second}/`) && !r.url().endsWith('/draft'));
  await page.locator('.composer:visible').getByRole('button', { name: '发送', exact: true }).click();
  assert.ok((await send).ok());
  assert.equal(count('jobs', second), 1);
  assert.equal(instance.db.sqlite.prepare("SELECT content FROM messages WHERE conversation_id=? AND role='user'").get(second).content, '最终手动发送的研究任务');
  report.checks.push('mobile_edit_and_explicit_send_creates_exactly_one_job_with_edited_content');
  assert.deepEqual(report.pageErrors, []); report.ok = true;
} finally {
  clearTimeout(deadline);
  fs.writeFileSync(output + '/result.json', JSON.stringify(report, null, 2));
  await browser?.close(); instance.beginShutdown(); await new Promise(r => server.close(r)); instance.db.close(); fs.rmSync(root, { recursive: true, force: true });
  console.log(JSON.stringify(report));
}
