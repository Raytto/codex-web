test("calendar rules use wall time, skip absent month dates, and handle DST gaps/folds", () => {
  assert.equal(nextOccurrence({ ...schedule, kind: "daily" }, start), "2026-10-10T01:00:00.000Z");
  assert.equal(nextOccurrence({ ...schedule, kind: "weekly" }, start), "2026-10-12T01:00:00.000Z");
  assert.equal(nextOccurrence({ ...schedule, kind: "monthly" }, Date.parse("2026-04-01T00:00Z")), "2026-05-31T01:00:00.000Z");
  const ny = { ...schedule, kind: "daily" as const, timeZone: "America/New_York", time: "02:30" };
  assert.equal(nextOccurrence(ny, Date.parse("2026-03-08T05:00Z")), "2026-03-09T06:30:00.000Z");
  assert.equal(nextOccurrence({ ...ny, time: "01:30" }, Date.parse("2026-11-01T04:00Z")), "2026-11-01T05:30:00.000Z");
  assert.equal(nextOccurrence({ ...ny, time: "01:30" }, Date.parse("2026-11-01T05:30Z")), "2026-11-02T06:30:00.000Z");
  assert.throws(() => validateRecurrence({ ...schedule, intervalMinutes: 0 }));
  assert.throws(() => validateRecurrence({ ...schedule, timeZone: "Mars" }));
  assert.throws(() => validateRecurrence({ ...schedule, kind: "weekly", weekdays: [] }));
});
test("a due occurrence is atomic, unique across connections and survives reopening", t => {
  const f = fixture(t), second = new AppDatabase(f.root, undefined, false), s2 = new RecurringStore(second);
  t.after(() => second.close());
  assert.equal(f.store.fire(LEGACY_USER_ID, f.task.id, start), null);
  const conversation = f.store.fire(LEGACY_USER_ID, f.task.id, start + 60000)!;
  assert.ok(conversation);
  assert.equal(s2.fire(LEGACY_USER_ID, f.task.id, start + 60000), null);
  assert.equal(s2.get(LEGACY_USER_ID, f.task.id)?.runCount, 1);
  assert.equal(s2.get(LEGACY_USER_ID, f.task.id)?.nextRunAt, "2026-10-10T00:02:00.000Z");
  const pending = f.db.listPendingPrompts(conversation)[0];
  const job = f.db.materializePendingPrompt(pending.id, id(), id())!;
  assert.equal(f.db.getMessage(job.message_id!)?.is_scheduled, 1);
  assert.equal(job.agent_model, input.model);
  assert.equal(job.reasoning_effort, input.reasoningEffort);
});
test("stopping or failing a run never cancels future schedules; overlap and downtime cannot pile up", t => {
  const f = fixture(t), user = LEGACY_USER_ID;
  const c1 = f.store.fire(user, f.task.id, start + 60000)!;
  assert.equal(f.store.fire(user, f.task.id, start + 120000), null);
  assert.equal(f.store.runs(user, f.task.id)[0].status, "skipped");
  assert.equal(f.store.get(user, f.task.id)?.runCount, 1);
  f.db.deletePendingPromptsForConversation(c1); // same persistence effect as Stop before dispatch
  const c2 = f.store.fire(user, f.task.id, start + 180000)!;
  const pending = f.db.listPendingPrompts(c2)[0], job = f.db.materializePendingPrompt(pending.id, id(), id())!;
  f.db.sqlite.prepare("UPDATE jobs SET status='failed' WHERE id=?").run(job.id);
  const c3 = f.store.fire(user, f.task.id, start + 86400000)!;
  assert.ok(c3); assert.notEqual(c3, c2);
  assert.equal(f.store.get(user, f.task.id)?.nextRunAt, "2026-10-11T00:01:00.000Z");
  assert.equal(f.store.get(user, f.task.id)?.runCount, 3);
  assert.equal(f.store.runs(user, f.task.id).length, 4);
});
test("rollback leaves no half-created conversation, queue item or advanced clock", t => {
  const f = fixture(t), create = f.db.createPendingPrompt.bind(f.db), before = f.db.listConversations().length;
  f.db.createPendingPrompt = () => { throw new Error("injected crash"); };
  assert.throws(() => f.store.fire(LEGACY_USER_ID, f.task.id, start + 60000), /injected/);
  assert.equal(f.db.listConversations().length, before); assert.equal(f.store.get(LEGACY_USER_ID, f.task.id)?.runCount, 0);
  f.db.createPendingPrompt = create;
  assert.ok(f.store.fire(LEGACY_USER_ID, f.task.id, start + 60000));
});
test("revision conflicts, pause/resume, finite counts, deletion and archived project are durable", t => {
  const f = fixture(t), user = LEGACY_USER_ID;
  const paused = f.store.update(user, f.task.id, 1, input, "paused", start)!;
  assert.equal(f.store.fire(user, f.task.id, start + 60000), null);
  assert.throws(() => f.store.update(user, f.task.id, 1, input, "active"), RecurringConflict);
  assert.throws(() => f.store.remove(user, f.task.id, 1), RecurringConflict);
  const limited = { ...input, maxRuns: 1 };
  const resumed = f.store.update(user, f.task.id, paused.revision, limited, "active", start + 86400000)!;
  assert.ok(f.store.fire(user, f.task.id, Date.parse(resumed.nextRunAt!)));
  const done = f.store.get(user, f.task.id)!;
  assert.equal(done.state, "completed"); assert.equal(done.nextRunAt, null);
  f.store.remove(user, done.id, done.revision);
  assert.equal(f.store.get(user, done.id), undefined); assert.ok(f.db.listConversations().length);
  const extra = f.store.create(user, f.project.id, input, start);
  f.db.archiveProjectForUser(f.project.id, user);
  assert.equal(f.store.due(start + 60000).length, 0);
  assert.equal(f.store.fire(user, extra.id, start + 60000), null);
});
